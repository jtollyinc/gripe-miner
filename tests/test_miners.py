class TestSlashCommands(Fixture):
    INVOKE = ("<command-message>deep-research is running…</command-message>\n"
              "<command-name>/deep-research</command-name>\n"
              "<command-args>solid state batteries</command-args>")
    BODY = ("# Deep research\n\nYou are a meticulous research assistant. Search the web for "
            "the topic given in the arguments, read at least five primary sources, and write "
            "a structured report with citations. Topic: solid state batteries")

    def test_command_invocation_parsing(self):
        self.assertEqual(command_invocation(self.INVOKE), "/deep-research solid state batteries")
        self.assertEqual(command_invocation("<command-name>/commit</command-name>"), "/commit")
        self.assertIsNone(command_invocation("run /deep-research on this"))
        self.assertIsNone(command_invocation("the transcript shows <command-name>/x</command-name> records"))

    def _run(self, body_extra):
        for i in range(3):
            self.session(f"s{i}", [
                user(self.INVOKE, self.at(3 - i), promptSource="typed", turnOrigin="human"),
                user(self.BODY, self.at(3 - i, 1), **body_extra),
                assistant(self.at(3 - i, 20), f"m{i}", out=400),
                user("ok now summarize that in three bullets", self.at(3 - i, 300),
                     promptSource="typed", turnOrigin="human"),
                assistant(self.at(3 - i, 310), f"n{i}", out=50),
            ])
        return list(iter_prompts([self.proj], self.cutoff(14)))

    def _check(self, prompts):
        self.assertEqual(len(prompts), 6)
        cmds = [p for p in prompts if p["origin"] == "command"]
        self.assertEqual(len(cmds), 3)
        self.assertTrue(all(p["text"] == "/deep-research solid state batteries" for p in cmds))
        self.assertTrue(all(p["usage"]["output"] == 400 for p in cmds), "body usage folds into the command")
        self.assertNotIn(self.BODY, [p["text"] for p in prompts])
        self.assertTrue(any("meticulous" not in p["text"] for p in prompts))
        humans = [p for p in prompts if p["origin"] == "human"]
        self.assertEqual([p["text"] for p in humans], ["ok now summarize that in three bullets"] * 3)
        clusters, stats = cluster(prompts)
        self.assertEqual(stats["skipped"]["command"], 3)
        self.assertEqual(stats["eligible"], 3)
        self.assertTrue(all("meticulous" not in m["text"] for c in clusters for m in c["members"]))
        clusters, stats = cluster(prompts, include_scripted=True)
        self.assertEqual(stats["skipped"]["command"], 0)
        self.assertEqual(stats["eligible"], 6)
        self.assertTrue(all(m["scripted"] for c in clusters for m in c["members"] if m["origin"] == "command"))

    def test_expansion_flagged_is_meta(self):
        self._check(self._run({"isMeta": True}))

    def test_expansion_without_is_meta_but_immediate(self):
        self._check(self._run({"promptSource": "typed", "turnOrigin": "human"}))

    def test_typed_message_after_a_bare_command_survives(self):
        self.session("s1", [
            user("<command-name>/clear</command-name><command-message>clear</command-message>", self.at(1)),
            user("rewrite the README install section for the namespaced commands", self.at(1, 45),
                 promptSource="typed", turnOrigin="human"),
            assistant(self.at(1, 50), "m1"),
        ])
        prompts = list(iter_prompts([self.proj], self.cutoff(14)))
        self.assertEqual([(p["origin"], p["text"][:20]) for p in prompts],
                         [("command", "/clear"), ("human", "rewrite the README i")])

    def test_mine_skips_command_bodies(self):
        self.session("s1", [
            user(self.INVOKE, self.at(1), promptSource="typed", turnOrigin="human"),
            user(self.BODY + " why does this keep breaking", self.at(1, 1), isMeta=True),
            user("why does this keep breaking every single time", self.at(1, 400),
                 promptSource="typed", turnOrigin="human"),
        ])
        hits, _ = mine([self.proj], self.cutoff(14), classify_gripe)
        self.assertEqual([h[1] for h in hits], ["why does this keep breaking every single time"])


